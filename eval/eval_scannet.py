"""ScanNet per-frame rotation evaluation (plain / rot)."""
import os
import sys
import warnings
import argparse
from datetime import timedelta

_local_redimatch_path = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, _local_redimatch_path)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
for k in list(sys.modules.keys()):
    if "redimatch" in k.lower():
        del sys.modules[k]

import torch
import torch.distributed as dist

from redimatch.benchmarks import ScanNetBenchmark, ScanNetRotBenchmark
_REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEIGHTS = os.path.join(_REPO, "models", "indoor.pth")

from _common import (
    _apply_fh_kw_to_decoder,
    _build_eval_model,
    install_gp_intrinsic_rotation_router,
    prepare_run_seed,
)

# Default local paths (override via CLI if your datasets live elsewhere).
# scans_rot: generated by an optional rot90 preparation utility, independently sampling {0,90,180,270} per frame.
DEFAULT_SCANNET_ROOT_PLAIN = os.path.join(_REPO, "data", "scannet", "scans")
DEFAULT_SCANNET_ROOT_ROT2 = os.path.join(_REPO, "data", "scannet", "scans_rot")
def _distributed_env() -> tuple[bool, int, int]:
    world_size = int(os.environ.get("WORLD_SIZE", "1"))
    distributed = world_size > 1
    if distributed:
        rank = int(os.environ["RANK"])
        local_rank = int(os.environ["LOCAL_RANK"])
    else:
        rank = 0
        local_rank = int(os.environ.get("LOCAL_RANK", "0"))
    return distributed, rank, local_rank

def _dist_init(distributed: bool, timeout_s: int) -> None:
    if not distributed:
        return
    dist.init_process_group(
        backend="nccl",
        timeout=timedelta(seconds=timeout_s),
    )

def ensure_results_dir():
    os.makedirs("results", exist_ok=True)

def _apply_cuda_eval_prefs(*, cudnn_benchmark: bool) -> None:
    if not torch.cuda.is_available():
        return
    torch.backends.cudnn.benchmark = bool(cudnn_benchmark)
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False
    try:
        torch.set_float32_matmul_precision("highest")
    except Exception:
        pass

def _set_c4(model, enabled: bool, *, perm_reverse: bool = True):
    dec = getattr(model, "decoder", None)
    if dec is None:
        return
    dec.c4_rotation_matching = bool(enabled)
    if enabled:
        dec.c4_perm_reverse = bool(perm_reverse)

def _set_c4_upsample_reuse_coarse_rot(model, reuse: bool) -> None:
    """Reuse coarse rot_idx during upsample, skip C4 re-estimation (requires ``upsample_preds=True``)."""
    dec = getattr(model, "decoder", None)
    if dec is None:
        return
    dec.c4_reuse_coarse_rot_on_upsample = bool(reuse)

def test_scannet(
    model,
    name: str,
    data_root: str,
    *,
    rank: int,
    rot: bool = False,
):
    bench_cls = ScanNetRotBenchmark if rot else ScanNetBenchmark
    scannet_benchmark = bench_cls(data_root)
    scannet_results = scannet_benchmark.benchmark(model)
    if rank != 0:
        return scannet_results
    print(f"[ScanNet] {name}")
    print(scannet_results)
    return scannet_results

def run_variant(
    *,
    args,
    device: str,
    rank: int,
    scannet_root_plain: str,
    scannet_root_rot2: str,
    weights_ckpt,
) -> list:

    split = getattr(args, "mode", "plain")
    summary = []
    for res in args.eval_resolutions:
        print("")
        print(
            f"[Eval] ScanNet | coarse_res={res} | "
            f"symmetric={args.symmetric} | upsample={args.upsample} | split={split} | "
            f"rot_match_mode={getattr(args, 'scannet_rot_match_mode', '?')}"
        )
        print("-" * 40)

        args.coarse_res = int(res)
        if split == "plain":
            model_plain = _build_eval_model(
                args,
                device,
                weights_ckpt,
                symmetric=bool(args.symmetric),
                upsample_preds=bool(args.upsample),
            )
            _set_c4(
                model_plain,
                False,
                perm_reverse=bool(True),
            )
            model_plain.h_resized = int(res)
            model_plain.w_resized = int(res)
            model_plain.train(False)
            name_plain = f"{args.experiment_prefix}_plain_r{res}"
            metrics_plain = test_scannet(model_plain, name_plain, data_root=scannet_root_plain, rank=rank)
            summary.append(
                {
                    "mode": "plain",
                    "resolution": int(res),
                    "experiment_name": name_plain,
                    "data_root": scannet_root_plain,
                    "c4_rotation_matching": False,
                    "metrics": metrics_plain,
                }
            )
            del model_plain
            torch.cuda.empty_cache()

        if split == "rot":
            model_rot = _build_eval_model(
                args,
                device,
                weights_ckpt,
                symmetric=bool(args.symmetric),
                upsample_preds=bool(args.upsample),
            )
            _set_c4(
                model_rot,
                True,
                perm_reverse=bool(True),
            )
            _set_c4_upsample_reuse_coarse_rot(
                model_rot, bool(getattr(args, "c4_reuse_coarse_rot_on_upsample", True))
            )
            if bool(args.upsample):
                print(
                    f"[C4] upsample reuses coarse rot_idx="
                    f"{bool(getattr(args, 'c4_reuse_coarse_rot_on_upsample', True))} "
                    f"(to disable re-estimation use --no-c4-reuse-coarse-rot-on-upsample)",
                    flush=True,
                )
            ok, _ = install_gp_intrinsic_rotation_router(model_rot)
            print(f"[C4] gp_intrinsic rotation router {'enabled' if ok else 'not available, fallback to default'}")
            model_rot.h_resized = int(res)
            model_rot.w_resized = int(res)
            model_rot.train(False)
            name_rot = f"{args.experiment_prefix}_rot_r{res}"
            rot_mode = getattr(args, "scannet_rot_match_mode", "gp")
            if rot_mode == "gp":
                _apply_fh_kw_to_decoder(
                    model_rot.decoder,
                    {
                        "hybrid_alpha": float(args.fh_hybrid_alpha),
                        "hybrid_temp": float(args.fh_hybrid_temp),
                        "margin_keep": float(args.fh_margin_keep),
                        "disagree_margin": float(args.fh_hybrid_disagree_margin),
                        "ot_pool_size": int(args.fh_ot_pool_size),
                        "ot_epsilon": float(args.fh_ot_epsilon),
                        "ot_iters": int(args.fh_ot_iters),
                    },
                )
            metrics_rot = test_scannet(
                model_rot,
                name_rot,
                data_root=scannet_root_rot2,
                rank=rank,
                rot=True,
            )
            summary.append(
                {
                    "mode": "rot",
                    "resolution": int(res),
                    "experiment_name": name_rot,
                    "data_root": scannet_root_rot2,
                    "c4_rotation_matching": True,
                    "c4_reuse_coarse_rot_on_upsample": bool(
                        getattr(args, "c4_reuse_coarse_rot_on_upsample", True)
                    ),
                    "scannet_rot_match_mode": rot_mode,
                    "metrics": metrics_rot,
                }
            )
            del model_rot
            torch.cuda.empty_cache()
    return summary

if __name__ == "__main__":
    warnings.filterwarnings("ignore", category=UserWarning, message="TypedStorage is deprecated")
    os.environ["TORCH_CUDNN_V8_API_ENABLED"] = "1"
    os.environ["OMP_NUM_THREADS"] = "16"

    p = argparse.ArgumentParser(
        description="ScanNet evaluation (plain + scans_rot)."
    )
    p.add_argument("--weights", type=str, default=WEIGHTS, help="merged model weights (pth)")
    p.add_argument(
        "--mode",
        type=str,
        choices=("plain", "rot"),
        default="plain",
        help="plain=scans only (C4 off, default); rot=scans_rot only (C4 on).",
    )
    p.add_argument(
        "--scannet_data_root",
        type=str,
        default=None,
        help="override plain Dataset root directory (scans)",
    )
    p.add_argument(
        "--scannet_data_root_rot",
        type=str,
        default=None,
        help="override rot2 Dataset root directory (default scans_rot, contains test.npz and scans_test/)",
    )
    p.add_argument(
        "--eval_resolutions",
        nargs="+",
        type=int,
        default=[576],
        help="match coarse resolution side length (h_resized=w_resized)",
    )
    p.add_argument("--upsample_res", type=int, default=1280)
    p.add_argument(
        "--experiment_prefix",
        type=str,
        default="scannet",
        help="display name prefix for eval runs",
    )
    p.add_argument("--symmetric", action=argparse.BooleanOptionalAction, default=True)
    p.add_argument("--upsample", action=argparse.BooleanOptionalAction, default=False)
    p.add_argument("--no_custom_corr", action="store_true", help="disable local_corr CUDA extension")
    p.add_argument("--c4_perm_reverse", action=argparse.BooleanOptionalAction, default=True)
    p.add_argument(
        "--c4-reuse-coarse-rot-on-upsample",
        action=argparse.BooleanOptionalAction,
        default=True,
        help=(
            "Default on: upsample stage reuses coarse match C4 rot_idx, skips hybrid/cos re-detection;"
            "If re-estimation during upsample is needed, pass --no-c4-reuse-coarse-rot-on-upsample"
        ),
    )
    p.add_argument(
        "--scannet_rot_match_mode",
        type=str,
        choices=("simple", "gp"),
        default="gp",
        help=(
            "rot2 branch only: simple=ScanNet original model.match (two paths);"
            "gp=consistent with Mega1500 FH: match(...,K1,K2,T_gt)+decoder c4_hybrid "
            "(requires gp_intrinsic router, already installed in rot branch)."
        ),
    )
    p.add_argument("--fh_hybrid_alpha", type=float, default=0.35)
    p.add_argument("--fh_hybrid_temp", type=float, default=0.05)
    p.add_argument("--fh_margin_keep", type=float, default=0.03)
    p.add_argument(
        "--fh_hybrid_disagree_margin",
        type=float,
        default=0.03,
        help="use hybrid when base!=hybrid and hybrid margin>=this; <=0 disables (consistent with Decoder.c4_hybrid_disagree_margin)",
    )
    p.add_argument(
        "--fh_ot_pool_size",
        type=int,
        default=12,
        help=(
            "In fundamental_hybrid, adaptive_avg_pool2d side length H=W applied to features before Sinkhorn;"
            "the number of grid points participating in OT is the square of this value."
        ),
    )
    p.add_argument("--fh_ot_epsilon", type=float, default=0.07)
    p.add_argument("--fh_ot_iters", type=int, default=10)
    p.add_argument(
        "--no_cudnn_benchmark",
        action="store_true",
        help="disable cudnn.benchmark (enabled by default)",
    )
    p.add_argument(
        "--seed",
        type=int,
        default=None,
        help="random seed",
    )
    p.add_argument(
        "--ddp_timeout_s",
        type=int,
        default=6 * 60 * 60,
        help="NCCL process group timeout (seconds) for torchrun multi-process; eval only runs on rank 0, other ranks wait at barrier",
    )
    args = p.parse_args()
    prepare_run_seed(args)

    distributed, rank, local_rank = _distributed_env()
    _dist_init(distributed, args.ddp_timeout_s)

    if not torch.cuda.is_available():
        if distributed:
            dist.destroy_process_group()
        raise RuntimeError("CUDA required")

    torch.cuda.set_device(local_rank)
    device = f"cuda:{local_rank}"
    _apply_cuda_eval_prefs(cudnn_benchmark=not args.no_cudnn_benchmark)

    scannet_root_plain = args.scannet_data_root or DEFAULT_SCANNET_ROOT_PLAIN
    scannet_root_rot2 = args.scannet_data_root_rot or DEFAULT_SCANNET_ROOT_ROT2

    init_path = os.path.abspath(os.path.expanduser(args.weights))
    if not os.path.isfile(init_path):
        if distributed:
            dist.destroy_process_group()
        raise FileNotFoundError(f"Weight file not found: {init_path}")
    _roots_to_check = []
    if args.mode == "plain":
        _roots_to_check.append(scannet_root_plain)
    if args.mode == "rot":
        _roots_to_check.append(scannet_root_rot2)
    for _root in _roots_to_check:
        test_npz = os.path.join(_root, "test.npz")
        if not os.path.isfile(test_npz):
            if distributed:
                dist.destroy_process_group()
            raise FileNotFoundError(
                f"not found {test_npz}；Please verify Dataset root directory points to a directory containing test.npz and scans_test/"
            )

    try:
        if rank == 0:
            ensure_results_dir()
            weights_ckpt = torch.load(init_path, map_location=device, weights_only=False)
            print(f"[Weights] {init_path}", flush=True)
            print(
                f"[Eval] ScanNet plain_root={scannet_root_plain} (C4 off) | rot2_root={scannet_root_rot2} (C4 on) | "
                f"symmetric={args.symmetric} upsample={args.upsample} seed={args.seed} | "
                f"mode={args.mode} | "
                f"scannet_rot_match_mode={args.scannet_rot_match_mode}",
                flush=True,
            )

            meta = {
                "weights_loaded_from": init_path,
                "mode": args.mode,
                "scannet_rot_match_mode": args.scannet_rot_match_mode,
                "fh_hybrid_alpha": args.fh_hybrid_alpha,
                "fh_hybrid_temp": args.fh_hybrid_temp,
                "fh_margin_keep": args.fh_margin_keep,
                "fh_hybrid_disagree_margin": args.fh_hybrid_disagree_margin,
                "fh_ot_pool_size": args.fh_ot_pool_size,
                "fh_ot_epsilon": args.fh_ot_epsilon,
                "fh_ot_iters": args.fh_ot_iters,
                "scannet_root_rot2": scannet_root_rot2,
                "c4_reuse_coarse_rot_on_upsample": bool(
                    getattr(args, "c4_reuse_coarse_rot_on_upsample", True)
                ),
                "distributed": distributed,
                "world_size": int(os.environ.get("WORLD_SIZE", "1")),
                "eval_rank": 0,
            }

            all_summaries = run_variant(
                args=args,
                device=device,
                rank=rank,
                scannet_root_plain=scannet_root_plain,
                scannet_root_rot2=scannet_root_rot2,
                weights_ckpt=weights_ckpt,
            )
            print("\n[Summary]")
            print({"meta": meta, "runs": all_summaries})

            print("[Done]", flush=True)

        if distributed:
            dist.barrier()
    finally:
        if distributed and dist.is_initialized():
            dist.destroy_process_group()
